//! `photolibd doctor schema`: compares the schema of a database with the one its applied migrations build.

use std::collections::BTreeSet;

use sqlx::{Executor, PgConnection, PgPool};

use crate::migrate::{BOOTSTRAP, Migration};

/// One line per table, column, constraint, index, view, trigger, function and enum of the current schema.
const DESCRIBE: &str = "
SELECT format('table %s', relname) FROM pg_class
WHERE relnamespace = current_schema()::regnamespace AND relkind IN ('r', 'p')
UNION ALL SELECT format('view %s %s', relname, pg_get_viewdef(oid)) FROM pg_class
WHERE relnamespace = current_schema()::regnamespace AND relkind IN ('v', 'm')
UNION ALL SELECT format('column %s.%s %s%s%s%s', c.relname, a.attname, format_type(a.atttypid, a.atttypmod),
  CASE a.attidentity WHEN 'a' THEN ' generated always as identity' WHEN 'd' THEN ' generated by default as identity'
  ELSE '' END, CASE WHEN a.attnotnull THEN ' not null' ELSE '' END,
  coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), ''))
FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE c.relnamespace = current_schema()::regnamespace AND c.relkind IN ('r', 'p') AND a.attnum > 0
  AND NOT a.attisdropped
UNION ALL SELECT format('constraint %s.%s %s', c.relname, con.conname, pg_get_constraintdef(con.oid))
FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid WHERE c.relnamespace = current_schema()::regnamespace
UNION ALL SELECT format('index %s', pg_get_indexdef(i.indexrelid))
FROM pg_index i JOIN pg_class c ON c.oid = i.indrelid WHERE c.relnamespace = current_schema()::regnamespace
UNION ALL SELECT format('trigger %s', pg_get_triggerdef(t.oid))
FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
WHERE c.relnamespace = current_schema()::regnamespace AND NOT t.tgisinternal
UNION ALL SELECT format('function %s', pg_get_functiondef(oid)) FROM pg_proc
WHERE pronamespace = current_schema()::regnamespace AND prokind IN ('f', 'p')
UNION ALL SELECT format('enum %s %s', t.typname,
  (SELECT string_agg(enumlabel, ',' ORDER BY enumsortorder) FROM pg_enum WHERE enumtypid = t.oid))
FROM pg_type t WHERE typnamespace = current_schema()::regnamespace AND typtype = 'e'";

async fn describe(conn: &mut PgConnection) -> sqlx::Result<BTreeSet<String>> {
    let schema: String = sqlx::query_scalar("SELECT current_schema()::text")
        .fetch_one(&mut *conn)
        .await?;
    let lines: Vec<String> = sqlx::query_scalar(DESCRIBE).fetch_all(&mut *conn).await?;
    Ok(lines
        .into_iter()
        .map(|line| line.replace(&format!("{schema}."), ""))
        .collect())
}

/// What differs between the database and the schema its applied migrations build, which is made in a scratch
/// schema and rolled back: `missing: …` lines for what the database lacks, `unexpected: …` for what it has on top.
pub async fn drift(pool: &PgPool, migrations: &[Migration]) -> sqlx::Result<Vec<String>> {
    let mut tx = pool.begin().await?;
    let actual = describe(&mut tx).await?;
    let migrated: Option<String> = sqlx::query_scalar("SELECT to_regclass('schema_migrations')::text")
        .fetch_one(&mut *tx)
        .await?;
    let applied: Vec<i64> = match migrated {
        Some(_) => {
            sqlx::query_scalar("SELECT version FROM schema_migrations")
                .fetch_all(&mut *tx)
                .await?
        }
        None => Vec::new(),
    };
    // Through `Executor`, unlike `RawSql::execute`, the future stays `Send` for the admin console.
    let scratch = "CREATE SCHEMA photolib_doctor; SET LOCAL search_path TO photolib_doctor";
    tx.execute(sqlx::raw_sql(scratch)).await?;
    tx.execute(sqlx::raw_sql(BOOTSTRAP)).await?;
    for m in migrations.iter().filter(|m| applied.contains(&m.version)) {
        tx.execute(sqlx::raw_sql(&m.sql)).await?;
    }
    let expected = describe(&mut tx).await?;
    tx.rollback().await?;
    let missing = expected.difference(&actual).map(|line| format!("missing: {line}"));
    let unexpected = actual.difference(&expected).map(|line| format!("unexpected: {line}"));
    Ok(missing.chain(unexpected).collect())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        migrate::{Upgrade, upgrade},
        testpg,
    };

    const SCHEMA: &str = "
        CREATE TABLE a (id int PRIMARY KEY);
        CREATE TABLE b (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, a_id int REFERENCES a (id),
                        note text NOT NULL DEFAULT 'x');
        CREATE INDEX b_a ON b (a_id);";

    #[tokio::test]
    async fn the_doctor_finds_what_differs_from_the_migrations() {
        let db = testpg::database().await;
        let migrations = [Migration::new("0001_ab.sql", SCHEMA).unwrap()];
        upgrade(&db.pool, &Upgrade::new(&migrations)).await.unwrap();
        assert_eq!(drift(&db.pool, &migrations).await.unwrap(), Vec::<String>::new());

        sqlx::raw_sql(
            "ALTER TABLE b ADD COLUMN extra int; DROP INDEX b_a; CREATE TABLE stray (x int);
             ALTER TABLE b ALTER COLUMN note DROP NOT NULL;",
        )
        .execute(&db.pool)
        .await
        .unwrap();
        assert_eq!(
            drift(&db.pool, &migrations).await.unwrap(),
            [
                "missing: column b.note text not null default 'x'::text",
                "missing: index CREATE INDEX b_a ON b USING btree (a_id)",
                "unexpected: column b.extra integer",
                "unexpected: column b.note text default 'x'::text",
                "unexpected: column stray.x integer",
                "unexpected: table stray",
            ]
        );
        let leftovers: i64 = sqlx::query_scalar("SELECT count(*) FROM pg_namespace WHERE nspname = 'photolib_doctor'")
            .fetch_one(&db.pool)
            .await
            .unwrap();
        assert_eq!(leftovers, 0, "the reference schema is rolled back");
    }
}

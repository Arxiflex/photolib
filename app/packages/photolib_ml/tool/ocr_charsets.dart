/// Writes lib/src/ocr_charsets.g.dart from the dictionaries of PP-OCRv5's
/// recognisers that the server compiles in, so that both read the same
/// characters: `dart run tool/ocr_charsets.dart` in `app/packages/photolib_ml`
/// after changing `server/crates/photolib-ml/data/ocr/`. The test
/// `ocr_test.dart` fails when the file is stale.
library;

import 'dart:io';

const scripts = {'latin': 'latin', 'eslav': 'eslav', 'chinese': 'chinese'};

/// The source of [dictionary] as Dart string literals, 64 lines to each.
String literal(String dictionary) {
  final lines = dictionary.split('\n').where((line) => line.isNotEmpty);
  final chunks = <String>[];
  final all = lines.toList();
  for (var i = 0; i < all.length; i += 64) {
    final chunk = all.skip(i).take(64).map((l) => '$l\n').join();
    final escaped = chunk
        .replaceAll(r'\', r'\\')
        .replaceAll("'", r"\'")
        .replaceAll(r'$', r'\$')
        .replaceAll('\n', r'\n');
    chunks.add("    '$escaped'");
  }
  return chunks.join('\n');
}

String generate(String Function(String name) read) {
  final out = StringBuffer(
    '// GENERATED by tool/ocr_charsets.dart from '
    'server/crates/photolib-ml/data/ocr/: do not edit.\n'
    '// ignore_for_file: lines_longer_than_80_chars, public_member_api_docs\n\n'
    "/// The characters of PP-OCRv5's recognisers, one a line.\n",
  );
  for (final name in scripts.keys) {
    out.write('const ${name}Dictionary =\n${literal(read(name))};\n\n');
  }
  return out.toString().trimRight();
}

/// The dictionary of [name], which the server compiles in.
String dictionary(String name) =>
    File('../../../server/crates/photolib-ml/data/ocr/$name.txt')
        .readAsStringSync();

void main() {
  File('lib/src/ocr_charsets.g.dart')
      .writeAsStringSync('${generate(dictionary)}\n');
}
